"""Entity map: maps entity names to SDK metadata, namespace, and method names.

Also provides ``get_operation_schema()`` for retrieving the compatibility
map entry for any entity + method combination.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _snake_to_camel(name: str) -> str:
    """Convert a snake_case method name to a camelCase operationId.

    Args:
        name: Snake-case string (e.g. ``"create_rsyslog_server"``).

    Returns:
        CamelCase string (e.g. ``"createRsyslogServer"``).
    """
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


_COMPAT_MAP_PATH = (
    Path(__file__).resolve().parent / "multi_namespace_compatibility_map.json"
)
_compat_cache: dict[str, Any] | None = None


def _load_compat_map() -> dict[str, Any]:
    """Load (and cache) the compatibility map JSON.

    Returns:
        The compatibility map dict (namespace -> operationId -> op_data).
    """
    global _compat_cache
    if _compat_cache is not None:
        return _compat_cache
    if not _COMPAT_MAP_PATH.exists():
        _compat_cache = {}
        return _compat_cache
    try:
        import orjson

        with open(_COMPAT_MAP_PATH, "rb") as fh:
            _compat_cache = orjson.loads(fh.read())
    except ImportError:
        with open(_COMPAT_MAP_PATH, encoding="utf-8") as fh:
            _compat_cache = json.load(fh)
    return _compat_cache


# Standard method-key suffixes in entity_map
_METHOD_KEYS = ("create", "get", "update", "delete", "list")


def get_operation_schema(
    entity_name: str,
    method_key: str = "create",
) -> dict[str, Any] | None:
    """Fetch the compatibility map schema for an entity's method.

    This translates an entity name and a human-readable method key
    (``"create"``, ``"update"``, ``"list"``, etc.) to the corresponding
    ``operationId`` and returns the full operation data from the
    compatibility map.

    Args:
        entity_name: Key in ``entity_map`` (e.g. ``"cluster_profile"``).
        method_key: One of ``"create"``, ``"update"``, ``"delete"``,
            ``"list"``, ``"get"``, or a custom operation name from the
            entity's ``"operations"`` list.

    Returns:
        The operation dict from the compatibility map (contains
        ``versions``, ``schema``, ``summary``, etc.) or ``None``
        if the entity or operation is not found.
    """
    entry = entity_map.get(entity_name)
    if entry is None:
        return None
    if not isinstance(entry, dict):
        return None

    namespace = entry.get("namespace", "")
    if not namespace:
        return None

    # Determine the snake_case method name
    if method_key in _METHOD_KEYS:
        method_name = entry.get(f"{method_key}_method_name", "")
    else:
        # Custom operation -- check the "operations" list
        operations = entry.get("operations", [])
        if method_key in operations:
            method_name = method_key
        else:
            return None

    if not method_name:
        return None

    operation_id = _snake_to_camel(method_name)

    compat_map = _load_compat_map()
    ns_ops = compat_map.get(namespace, {})
    return ns_ops.get(operation_id)


